-- ============================================================
-- Script : oltp_schema.sql
-- Descripción : Creación e inserción de datos OLTP
--               Tablas: clientes, productos, ventas
-- Motor : MySQL 8+
-- ============================================================

CREATE DATABASE IF NOT EXISTS oltp_ventas
    CHARACTER SET utf8mb4
    COLLATE utf8mb4_spanish_ci;

USE oltp_ventas;

-- ------------------------------------------------------------
-- Tabla: clientes
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS clientes (
    ID_Cliente     INT          NOT NULL,
    Nombre         VARCHAR(100) NOT NULL,
    Correo         VARCHAR(150) NOT NULL,
    Ciudad         VARCHAR(60)  NOT NULL,
    Fecha_Registro DATE         NOT NULL,
    Tipo_Cliente   VARCHAR(10)  NOT NULL,
    CONSTRAINT pk_clientes      PRIMARY KEY (ID_Cliente),
    CONSTRAINT chk_tipo_cliente CHECK (Tipo_Cliente IN ('Premium', 'Estándar', 'Básico'))
);

-- ------------------------------------------------------------
-- Tabla: productos
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS productos (
    Cod_Producto INT          NOT NULL,
    Descripcion  VARCHAR(100) NOT NULL,
    Linea        VARCHAR(50)  NOT NULL,
    Costo_CLP    INT          NOT NULL,
    Precio_Venta INT          NOT NULL,
    Stock_Actual INT          NOT NULL DEFAULT 0,
    Activo       CHAR(2)      NOT NULL DEFAULT 'SI',
    CONSTRAINT pk_productos  PRIMARY KEY (Cod_Producto),
    CONSTRAINT chk_activo    CHECK (Activo IN ('SI', 'NO')),
    CONSTRAINT chk_costo     CHECK (Costo_CLP    >= 0),
    CONSTRAINT chk_precio    CHECK (Precio_Venta >= 0),
    CONSTRAINT chk_stock     CHECK (Stock_Actual >= 0)
);

-- ------------------------------------------------------------
-- Tabla: ventas
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS ventas (
    ID_Venta    INT  NOT NULL,
    Fecha_Venta DATE NOT NULL,
    ID_Cliente  INT  NOT NULL,
    Cod_Prod    INT  NOT NULL,
    Cant        INT  NOT NULL,
    Precio_Unit INT  NOT NULL,
    Desc_Pct    INT  NOT NULL DEFAULT 0,
    Total_Venta INT  NOT NULL,
    CONSTRAINT pk_ventas           PRIMARY KEY (ID_Venta),
    CONSTRAINT fk_ventas_clientes  FOREIGN KEY (ID_Cliente) REFERENCES clientes  (ID_Cliente),
    CONSTRAINT fk_ventas_productos FOREIGN KEY (Cod_Prod)   REFERENCES productos (Cod_Producto),
    CONSTRAINT chk_cant            CHECK (Cant      >= 1),
    CONSTRAINT chk_desc_pct        CHECK (Desc_Pct  BETWEEN 0 AND 100),
    CONSTRAINT chk_total           CHECK (Total_Venta >= 0)
);

